describe('Spec 022 — AC-7: SceneValidationError on missing required field', () => {
  let tmpFile: string;

  beforeEach(() => {
    ensureTmpDir();
    tmpFile = join(TMP_DIR, 'malformed-scene.yaml');
    writeFileSync(tmpFile, MALFORMED_YAML, 'utf-8');
  });

  afterEach(cleanupTmpDir);

  it('throws SceneValidationError with file path and JSON Pointer path', async () => {
    try {
      await loadSceneFile(tmpFile);
      expect.fail('Should have thrown SceneValidationError');
    } catch (err) {
      expect(err).toBeInstanceOf(SceneValidationError);
      const e = err as SceneValidationError;
      expect(e.filePath).toBe(tmpFile);
      expect(e.errors.length).toBeGreaterThan(0);
      // The error should reference /rooms/0/name (missing name)
      const errorStrings = e.errors.map((er) => er.instancePath + ': ' + er.message).join('\n');
      expect(errorStrings).toContain('/rooms/0');
      expect(errorStrings.toLowerCase()).toContain('name');
      // rawObject should be present for debugging
      expect(e.rawObject).toBeDefined();
    }
  });
});

