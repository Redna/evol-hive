describe('Spec 022 — AC-1: JSON Schema file exists', () => {
  it('scene-schema.json exists at packages/shared/src/schemas/scene-schema.json', () => {
    const schemaPath = join(REPO_ROOT, 'packages/shared/src/schemas/scene-schema.json');
    expect(existsSync(schemaPath)).toBe(true);
  });

  it('scene-schema.json is a valid Draft 2020-12 JSON Schema', () => {
    const schemaPath = join(REPO_ROOT, 'packages/shared/src/schemas/scene-schema.json');
    const schema = JSON.parse(require('node:fs').readFileSync(schemaPath, 'utf-8'));
    expect(schema['$schema']).toBe('https://json-schema.org/draft/2020-12/schema');
    expect(schema.type).toBe('object');
    expect(schema.properties.rooms).toBeDefined();
    expect(schema.properties.objects).toBeDefined();
    expect(schema.properties.agents).toBeDefined();
  });

  it('validateSceneObject accepts a valid SceneDefinition structure', () => {
    const obj = yaml.load(VALID_YAML);
    const scene = validateSceneObject(obj);
    expect(scene.id).toBe('test-scene');
    expect(scene.rooms).toHaveLength(2);
    expect(scene.objects).toHaveLength(2);
    expect(scene.agents).toHaveLength(1);
  });
});

