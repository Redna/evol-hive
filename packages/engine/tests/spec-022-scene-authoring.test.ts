// ─── Handler plugin system tests (AC-9, AC-10) ─────────────────────────────

describe('Spec 022 — AC-9: Affordance handler auto-registration', () => {
  let tmpFile: string;
  let core: EngineCore;

  beforeEach(() => {
    ensureTmpDir();
    tmpFile = join(TMP_DIR, 'test-scene.yaml');
    writeFileSync(tmpFile, VALID_YAML, 'utf-8');
    core = createEngineCore({
      fps: 60,
      spatialDebounceSeconds: 5,
      maxConcurrentLLM: 1,
    });
    clearHandlerPlugins();
    // Register built-in plugins that include handlers for 'relax' (furniture type)
    createBuiltinPlugins().forEach(registerHandlerPlugin);
  });

  afterEach(() => {
    cleanupTmpDir();
    clearHandlerPlugins();
  });

  it('after auto-registration, all affordances have registered engineEffect handlers', async () => {
    const scene = await loadSceneFile(tmpFile);
    loadScene(core, scene);
    autoRegisterHandlers(core, scene);

    // Check every affordance in the scene has a registered handler
    for (const obj of scene.objects) {
      for (const aff of obj.affordances) {
        const handler = core.affordanceRegistry.getHandler(aff.engineEffect);
        expect(handler, `Handler for "${aff.engineEffect}" should be registered`).not.toBeNull();
      }
    }
  });
});

describe('Spec 022 — AC-10: Custom HandlerPlugin for custom object type', () => {
  let tmpFile: string;
  let core: EngineCore;

  const CUSTOM_YAML = `
id: custom-scene
name: Custom Scene
rooms:
  - id: room-1
    name: Room One
    description: A room.
    connections: []
    objectIds:
      - device-1
objects:
  - id: device-1
    name: Custom Device
    type: custom_device
    state:
      power: 100
    roomId: room-1
    affordances:
      - id: activate
        label: Activate device
        engineEffect: activate
        preconditions: []
        effects:
          energy: 10
agents: []
`;

  beforeEach(() => {
    ensureTmpDir();
    tmpFile = join(TMP_DIR, 'custom-scene.yaml');
    writeFileSync(tmpFile, CUSTOM_YAML, 'utf-8');
    core = createEngineCore({
      fps: 60,
      spatialDebounceSeconds: 5,
      maxConcurrentLLM: 1,
    });
    clearHandlerPlugins();
  });

  afterEach(() => {
    cleanupTmpDir();
    clearHandlerPlugins();
  });

  it('custom HandlerPlugin for custom_device provides auto-registered handlers', async () => {
    const customPlugin: HandlerPlugin = {
      objectType: 'custom_device',
      handlers: {
        activate: async (_objId, _agentId, state) => ({
          success: true,
          newState: state,
          driveChanges: { energy: 10 },
        }),
      },
    };
    registerHandlerPlugin(customPlugin);

    const scene = await loadSceneFile(tmpFile);
    loadScene(core, scene);
    autoRegisterHandlers(core, scene);

    const handler = core.affordanceRegistry.getHandler('activate');
    expect(handler).not.toBeNull();
    const result = await handler!('device-1', 'agent-x', { power: 100 });
    expect(result.success).toBe(true);
  });
});

// ─── Doorway auto-generation tests (AC-11) ──────────────────────────────────

describe('Spec 022 — AC-11: Doorway auto-generation', () => {
  let tmpFile: string;

  beforeEach(() => {
    ensureTmpDir();
    tmpFile = join(TMP_DIR, 'doorway-scene.yaml');
    writeFileSync(tmpFile, DOORWAY_YAML, 'utf-8');
  });

  afterEach(cleanupTmpDir);

  it('auto-generates doorway objects for rooms with connections but no doorway', async () => {
    const scene = await loadSceneFile(tmpFile);
    // The original YAML had no objects, but doorways should be auto-generated
    expect(scene.objects.length).toBeGreaterThan(0);

    // Check for doorway-living_room with go_to_kitchen affordance
    const livingRoomDoorway = scene.objects.find((o) => o.id === 'doorway-living_room');
    expect(livingRoomDoorway).toBeDefined();
    expect(livingRoomDoorway!.type).toBe('doorway');
    expect(livingRoomDoorway!.roomId).toBe('living_room');
    const goToKitchen = livingRoomDoorway!.affordances.find((a) => a.id === 'go_to_kitchen');
    expect(goToKitchen).toBeDefined();
    expect(goToKitchen!.engineEffect).toBe('go_to_kitchen');

    // Check for doorway-kitchen with go_to_living_room affordance
    const kitchenDoorway = scene.objects.find((o) => o.id === 'doorway-kitchen');
    expect(kitchenDoorway).toBeDefined();
    const goToLivingRoom = kitchenDoorway!.affordances.find((a) => a.id === 'go_to_living_room');
    expect(goToLivingRoom).toBeDefined();
  });

  it('does not auto-generate doorway if doorway already exists in objectIds', async () => {
    const yamlWithExistingDoorway = `
id: existing-doorway-scene
name: Existing Doorway Scene
rooms:
  - id: room-a
    name: Room A
    description: Room A.
    connections:
      - room-b
    objectIds:
      - doorway-room-a
objects:
  - id: doorway-room-a
    name: Doorway
    type: doorway
    state: {}
    roomId: room-a
    affordances:
      - id: go_to_room-b
        label: Go to Room B
        engineEffect: go_to_room-b
        preconditions: []
        effects: {}
agents: []
`;
    const existingFile = join(TMP_DIR, 'existing-doorway.yaml');
    writeFileSync(existingFile, yamlWithExistingDoorway, 'utf-8');
    const scene = await loadSceneFile(existingFile);
    // Should still have exactly 1 doorway (not duplicated)
    const doorways = scene.objects.filter((o) => o.id === 'doorway-room-a');
    expect(doorways).toHaveLength(1);
  });
});

